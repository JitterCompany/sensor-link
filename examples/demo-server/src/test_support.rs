/// A store call recorded by [`MockDeviceStore`].
#[derive(Debug, Clone, PartialEq)]
pub enum StoreCall {
    DeviceById {
        device_id: String,
    },
    SetDeviceField {
        device_id: String,
        field: RecordedField,
    },
    SetFieldForDevices {
        device_ids: Vec<String>,
        field: RecordedField,
    },
}

/// The value of a recorded [`DeviceFieldType`].
///
/// `DeviceFieldType` is generated by a derive macro and implements neither
/// `Debug` nor `PartialEq`, so calls are recorded as this comparable stand-in.
/// Variants only exist for the fields the tests care about; everything else is
/// recorded by field name.
#[derive(Debug, Clone, PartialEq)]
pub enum RecordedField {
    ConfigConfirmed(bool),
    ConfigLastSentAt(Option<i64>),
    Other(&'static str),
}

impl From<&DeviceFieldType> for RecordedField {
    fn from(value: &DeviceFieldType) -> Self {
        match value {
            DeviceFieldType::ConfigConfirmed(v) => Self::ConfigConfirmed(*v),
            DeviceFieldType::ConfigLastSentAt(v) => Self::ConfigLastSentAt(*v),
            other => Self::Other(other.field_name()),
        }
    }
}

/// In-memory [`DeviceSettingsStore`] that records every call made to it.
///
/// Only the reads used by the code under test return data (configured up front
/// with [`MockDeviceStore::with_settings`] / [`MockDeviceStore::with_device`]);
/// writes are recorded and discarded. Methods that no test exercises panic, so
/// an unexpected store access fails the test rather than passing silently.
#[derive(Default)]
pub struct MockDeviceStore {
    settings: Option<Settings>,
    device: Option<Device>,
    calls: Mutex<Vec<StoreCall>>,
}

impl MockDeviceStore {
    pub fn new() -> Self {
        Self::default()
    }

    /// Settings returned by [`DeviceSettingsStore::settings_by_device_id`].
    pub fn with_settings(mut self, settings: Settings) -> Self {
        self.settings = Some(settings);
        self
    }

    /// Device returned by [`DeviceStore::device_by_id`].
    pub fn with_device(mut self, device: Device) -> Self {
        self.device = Some(device);
        self
    }

    /// All calls made so far, in call order.
    pub fn calls(&self) -> Vec<StoreCall> {
        self.calls.lock().unwrap().clone()
    }

    /// Assert the exact sequence of calls made so far.
    #[track_caller]
    pub fn assert_calls(&self, expected: &[StoreCall]) {
        assert_eq!(self.calls(), expected);
    }

    fn record(&self, call: StoreCall) {
        self.calls.lock().unwrap().push(call);
    }
}

/// A firmware inserted into [`MockFirmwareStore`].
///
/// [`NewFirmware`] is neither `Clone` nor `PartialEq`, so inserts are kept as
/// this stand-in with the same fields.
#[derive(Debug, Clone, PartialEq)]
#[allow(non_snake_case)]
pub struct InsertedFirmware {
    pub version: String,
    pub description: String,
    pub date: chrono::DateTime<chrono::Utc>,
    pub v2BinID: String,
    pub recommended: bool,
    pub device_type: DeviceType,
}

impl From<NewFirmware> for InsertedFirmware {
    fn from(firmware: NewFirmware) -> Self {
        Self {
            version: firmware.version,
            description: firmware.description,
            date: firmware.date,
            v2BinID: firmware.v2BinID,
            recommended: firmware.recommended,
            device_type: firmware.device_type,
        }
    }
}

/// In-memory [`FirmwareStore`] holding the firmwares inserted into it.
///
/// Inserts get a sequential id and are returned by `get_firmwares` like a real
/// store would; removed firmwares are dropped from that read but kept in
/// [`inserted`](MockFirmwareStore::inserted), so a test can tell an insert that
/// was later removed from one that never happened. Methods that no test
/// exercises panic, so an unexpected store access fails the test rather than
/// passing silently.
#[derive(Default, Clone)]
pub struct MockFirmwareStore {
    inserted: Arc<Mutex<Vec<InsertedFirmware>>>,
    removed_ids: Arc<Mutex<Vec<String>>>,
}

impl MockFirmwareStore {
    pub fn new() -> Self {
        Self::default()
    }

    /// All firmwares inserted so far, in insertion order, including the ones
    /// removed again.
    pub fn inserted(&self) -> Vec<InsertedFirmware> {
        self.inserted.lock().unwrap().clone()
    }

    /// The firmwares still stored, in insertion order.
    pub fn stored(&self) -> Vec<InsertedFirmware> {
        let removed_ids = self.removed_ids.lock().unwrap();
        self.inserted
            .lock()
            .unwrap()
            .iter()
            .enumerate()
            .filter(|(index, _)| !removed_ids.contains(&index.to_string()))
            .map(|(_, firmware)| firmware.clone())
            .collect()
    }
}

#[async_trait]
impl FirmwareStore for MockFirmwareStore {
    type DeviceType = DeviceType;

    async fn insert_firmware(&self, firmware: NewFirmware) -> Result<()> {
        self.inserted.lock().unwrap().push(firmware.into());
        Ok(())
    }

    async fn get_firmwares(&self, device_type: &Self::DeviceType) -> Result<Vec<Firmware>> {
        let removed_ids = self.removed_ids.lock().unwrap();
        Ok(self
            .inserted
            .lock()
            .unwrap()
            .iter()
            .enumerate()
            .filter(|(index, firmware)| {
                firmware.device_type == *device_type && !removed_ids.contains(&index.to_string())
            })
            .map(|(index, firmware)| Firmware {
                id: index.to_string(),
                version: firmware.version.clone(),
                description: firmware.description.clone(),
                date: firmware.date,
                v2BinID: firmware.v2BinID.clone(),
                recommended: firmware.recommended,
                device_type: firmware.device_type,
            })
            .collect())
    }

    async fn firmware_by_id(&self, _id: &DataStoreId) -> Result<Option<Firmware>> {
        unimplemented!("MockFirmwareStore::firmware_by_id")
    }

    async fn remove_firmware(&self, id: &DataStoreId) -> Result<()> {
        self.removed_ids.lock().unwrap().push(id.clone());
        Ok(())
    }

    async fn recommend_firmware(&self, _id: &DataStoreId) -> Result<()> {
        unimplemented!("MockFirmwareStore::recommend_firmware")
    }

    async fn unrecommend_other_firmwares_for_same_device_type(
        &self,
        _id: &DataStoreId,
    ) -> Result<()> {
        unimplemented!("MockFirmwareStore::unrecommend_other_firmwares_for_same_device_type")
    }
}

