#!/usr/bin/env bash
# Regenerate the Tables section of database.md from a live database.
#
# Renders every table in the public schema (columns, types, comments, keys and
# TimescaleDB policies) into the marker region of the doc. The comments come
# from the COMMENT ON statements in the migrations, so the schema is the single
# source of truth. CI runs this against a fresh database and fails when the
# committed doc is stale.
#
# Usage: point DATABASE_URL at a database with all migrations applied
# (defaults to the local dev database from dev/docker-compose.yml) and run
# the script; it rewrites database.md in place.
set -euo pipefail

DATABASE_URL="${DATABASE_URL:-postgres://demo:demo@localhost:5433/demo}"
DOC="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/database.md"

BEGIN='<!-- BEGIN GENERATED TABLES (generated by scripts/generate-db-docs.sh; do not edit by hand) -->'
END='<!-- END GENERATED TABLES -->'

grep -qF "$BEGIN" "$DOC" || { echo "Marker not found in $DOC"; exit 1; }

block=$(psql "$DATABASE_URL" -X -q -At -v ON_ERROR_STOP=1 <<'SQL'
WITH tables AS (
    SELECT c.oid, c.relname AS name
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r'
      AND c.relname <> '__diesel_schema_migrations'  -- diesel bookkeeping
),
cols AS (
    SELECT t.oid, string_agg(
        '| `' || a.attname || '` | `' || format_type(a.atttypid, a.atttypmod)
        || '` | ' || CASE WHEN a.attnotnull THEN 'no' ELSE 'yes' END || ' | '
        || coalesce(col_description(t.oid, a.attnum), '') || ' |',
        E'\n' ORDER BY a.attnum) AS body
    FROM tables t
    JOIN pg_attribute a ON a.attrelid = t.oid
    WHERE a.attnum > 0 AND NOT a.attisdropped
    GROUP BY t.oid
),
cons AS (
    -- 'p' sorts after 'f', so DESC puts the primary key first
    SELECT conrelid AS oid, string_agg(
        '- `' || pg_get_constraintdef(c.oid, true) || '`',
        E'\n' ORDER BY c.contype DESC) AS body
    FROM pg_constraint c
    WHERE c.contype IN ('p', 'f') AND c.conrelid IN (SELECT oid FROM tables)
    GROUP BY conrelid
),
ts AS (
    SELECT h.hypertable_name AS name,
        '- Hypertable partitioned on `' || d.column_name || '`'
        || coalesce('; compressed after ' || (cj.config->>'compress_after')
            || coalesce(' (segmented by `' || cs.segmentby || '`)', ''), '')
        || coalesce('; retention: dropped after ' || (rj.config->>'drop_after'),
                    '; retention: none, kept indefinitely')
        AS body
    FROM timescaledb_information.hypertables h
    JOIN timescaledb_information.dimensions d
        ON d.hypertable_name = h.hypertable_name AND d.dimension_number = 1
    LEFT JOIN timescaledb_information.hypertable_compression_settings cs
        ON cs.hypertable = format('%I.%I', h.hypertable_schema, h.hypertable_name)::regclass
    LEFT JOIN timescaledb_information.jobs cj
        ON cj.hypertable_name = h.hypertable_name AND cj.proc_name = 'policy_compression'
    LEFT JOIN timescaledb_information.jobs rj
        ON rj.hypertable_name = h.hypertable_name AND rj.proc_name = 'policy_retention'
    WHERE h.hypertable_schema = 'public'
)
SELECT string_agg(
    '### ' || t.name || E'\n\n'
    || coalesce(obj_description(t.oid, 'pg_class') || E'\n\n', '')
    || E'| Column | Type | Nullable | Description |\n'
    || E'|---|---|---|---|\n'
    || cols.body || E'\n\n'
    || cons.body
    || coalesce(E'\n' || ts.body, ''),
    E'\n\n' ORDER BY t.name)
FROM tables t
JOIN cols ON cols.oid = t.oid
JOIN cons ON cons.oid = t.oid
LEFT JOIN ts ON ts.name = t.name;
SQL
)

# The block goes through the environment: awk -v would mangle backslashes.
BLOCK="$block" awk -v begin="$BEGIN" -v end="$END" '
    index($0, begin) { print; print ""; print ENVIRON["BLOCK"]; print ""; skip = 1; next }
    index($0, end)   { skip = 0 }
    !skip            { print }
' "$DOC" > "$DOC.tmp"
mv "$DOC.tmp" "$DOC"

echo "Updated $DOC"
